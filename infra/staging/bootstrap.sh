#!/usr/bin/env bash
# One-time (and re-runnable) setup of FTTH Site Tracker staging on the shared Hetzner server (ADR-010).
# Run as root from the Hetzner web console:
#   curl -fsSL https://raw.githubusercontent.com/pillarsolution2026-CM/ftth-site-tracker/main/infra/staging/bootstrap.sh \
#     | ADMIN_EMAIL=you@example.com bash
# It never edits other apps: it only appends one `import` line to /etc/caddy/Caddyfile (validated, with
# automatic rollback) and keeps everything else under /srv/ftth, user ftth-deploy and compose project ftth-staging.
set -euo pipefail

readonly REPO_URL="${FTTH_REPO_URL:-https://github.com/pillarsolution2026-CM/ftth-site-tracker.git}"
readonly ROOT="${FTTH_ROOT:-/srv/ftth}"
readonly APP="$ROOT/app"
readonly ENV_FILE="$ROOT/.env"
readonly SNIPPET="$ROOT/ftthtracker.caddy"
readonly CADDYFILE="${CADDYFILE:-/etc/caddy/Caddyfile}"
readonly DEPLOY_USER=ftth-deploy
readonly APP_DOMAIN=staging.ftthtracker.projectflow.site
readonly API_DOMAIN=api.staging.ftthtracker.projectflow.site
readonly IMAGE_REGISTRY=ghcr.io/pillarsolution2026-cm/ftth-site-tracker

step() { printf '\n\033[1;34m==> %s\033[0m\n' "$*"; }
warn() { printf '\033[1;33m!! %s\033[0m\n' "$*"; }
die() { printf '\033[1;31mXX %s\033[0m\n' "$*" >&2; exit 1; }
as_deploy() { runuser -u "$DEPLOY_USER" -- "$@"; }
random_secret() { openssl rand -hex 32; }
env_get() { sed -n "s/^$1=//p" "$ENV_FILE" 2>/dev/null | tail -n 1; }
port_in_use() { [[ -n "$(ss -Htln "sport = :$1")" ]]; }

next_free_port() {
  local port=$1
  while port_in_use "$port" || [[ "$port" == "${2:-}" ]]; do port=$((port + 1)); done
  echo "$port"
}

step "Preflight / فحص السيرفر"
[[ $EUID -eq 0 ]] || die "Run as root (sudo). / شغّل الأمر كـ root."
# runuser keeps the caller's cwd; ftth-deploy can't read /root, so docker compose fails with "stat .: permission denied".
cd /
command -v docker >/dev/null || die "Docker is not installed. / Docker مش متثبت."
docker compose version >/dev/null 2>&1 || die "Docker Compose v2 is missing. / docker compose مش موجود."
command -v caddy >/dev/null || die "Caddy binary not found on the host. / Caddy مش متثبت على السيرفر."
[[ -f "$CADDYFILE" ]] || die "$CADDYFILE not found. / ملف Caddy مش موجود."
systemctl is-active --quiet caddy || die "Caddy service is not running. / خدمة Caddy مش شغالة."
for tool in git openssl ss curl flock runuser; do
  command -v "$tool" >/dev/null || die "Missing tool: $tool"
done
echo "ok"

step "User and folders / المستخدم والفولدرات"
if ! id "$DEPLOY_USER" >/dev/null 2>&1; then
  useradd --system --create-home --shell /usr/sbin/nologin --groups docker "$DEPLOY_USER"
fi
usermod -aG docker "$DEPLOY_USER"
install -d -o "$DEPLOY_USER" -g "$DEPLOY_USER" -m 755 "$ROOT"
install -d -o "$DEPLOY_USER" -g "$DEPLOY_USER" -m 750 "$ROOT/backups"
if [[ -d "$APP/.git" ]]; then
  as_deploy git -C "$APP" fetch --quiet origin main
else
  as_deploy git clone --quiet "$REPO_URL" "$APP"
fi
echo "ok: $ROOT"

step "Secrets (.env) / الأسرار"
if [[ -f "$ENV_FILE" ]]; then
  echo "kept existing $ENV_FILE"
else
  web_port=$(next_free_port 3310)
  api_port=$(next_free_port $((web_port + 1)) "$web_port")
  umask 077
  cat >"$ENV_FILE" <<ENV
# Generated by bootstrap.sh on $(date -u +%F). Keep private.
APP_DOMAIN=$APP_DOMAIN
API_DOMAIN=$API_DOMAIN
WEB_PORT=$web_port
API_PORT=$api_port
BACKUP_DIR=$ROOT/backups
IMAGE_REGISTRY=$IMAGE_REGISTRY
IMAGE_TAG=staging
POSTGRES_USER=ftth
POSTGRES_PASSWORD=$(random_secret)
POSTGRES_DB=ftth
REDIS_PASSWORD=$(random_secret)
JWT_ACCESS_SECRET=$(random_secret)
# Hetzner Object Storage: not used before Phase 1 uploads; replace when buckets exist.
S3_ENDPOINT=https://fsn1.your-objectstorage.com
S3_BUCKET=ftth-staging
S3_ACCESS_KEY=not-configured
S3_SECRET_KEY=not-configured
ENV
  umask 022
  chown "$DEPLOY_USER:$DEPLOY_USER" "$ENV_FILE"
  chmod 600 "$ENV_FILE"
  echo "created $ENV_FILE"
fi
web_port=$(env_get WEB_PORT)
api_port=$(env_get API_PORT)
echo "web -> 127.0.0.1:$web_port, api -> 127.0.0.1:$api_port"

# Tiles (ADR-031): also added to a server bootstrapped earlier, leaving its other secrets alone.
deploy_args=()
[[ -n "$(env_get MARTIN_PORT)" ]] || printf 'MARTIN_PORT=%s\n' "$(next_free_port $((api_port + 1)) "$web_port")" >>"$ENV_FILE"
[[ -n "$(env_get FTTH_TILES_PASSWORD)" ]] || printf 'FTTH_TILES_PASSWORD=%s\n' "$(random_secret)" >>"$ENV_FILE"
if [[ -z "$(env_get TILE_URL_SECRET)" ]]; then
  printf 'TILE_URL_SECRET=%s\nTILES_PUBLIC_URL=https://%s\n' "$(random_secret)" "$API_DOMAIN" >>"$ENV_FILE"
  deploy_args=(--force) # the running API must be recreated to read them
fi
martin_port=$(env_get MARTIN_PORT)
echo "martin -> 127.0.0.1:$martin_port"

step "Caddy (import + validate + reload) / ربط Caddy"
sed -e "s/__WEB_PORT__/$web_port/" -e "s/__API_PORT__/$api_port/" -e "s/__MARTIN_PORT__/$martin_port/" \
  "$APP/infra/staging/ftthtracker.caddy.template" >"$SNIPPET.new"
chmod 644 "$SNIPPET.new"
backup="$CADDYFILE.bak.ftth.$(date +%F-%H%M%S)"
cp -a "$CADDYFILE" "$backup"
[[ -f "$SNIPPET" ]] && cp -a "$SNIPPET" "$SNIPPET.prev"
mv "$SNIPPET.new" "$SNIPPET"
import_line="import $SNIPPET"
if ! grep -qxF "$import_line" "$CADDYFILE"; then
  printf '\n# FTTH Site Tracker staging (added by %s/app/infra/staging/bootstrap.sh)\n%s\n' "$ROOT" "$import_line" >>"$CADDYFILE"
fi
if caddy validate --config "$CADDYFILE" --adapter caddyfile >/tmp/ftth-caddy-validate.log 2>&1; then
  systemctl reload caddy
  echo "Caddy reloaded (backup: $backup)"
else
  cp -a "$backup" "$CADDYFILE"
  if [[ -f "$SNIPPET.prev" ]]; then mv "$SNIPPET.prev" "$SNIPPET"; else rm -f "$SNIPPET"; fi
  cat /tmp/ftth-caddy-validate.log >&2
  die "Caddy validation failed; restored the previous Caddyfile, nothing reloaded. / رجّعت إعدادات Caddy زي ما كانت."
fi
rm -f "$SNIPPET.prev"

step "Auto-deploy timer / الـdeploy التلقائي"
install -o root -g root -m 755 "$APP/infra/staging/autodeploy.sh" /usr/local/bin/ftth-autodeploy
install -o root -g root -m 644 "$APP/infra/staging/systemd/ftth-autodeploy.service" /etc/systemd/system/
install -o root -g root -m 644 "$APP/infra/staging/systemd/ftth-autodeploy.timer" /etc/systemd/system/
systemctl daemon-reload
systemctl enable --now ftth-autodeploy.timer
echo "timer enabled (every 2 minutes)"

step "First deploy / أول تشغيل"
# The timer may be mid-deploy: autodeploy would then exit at once and a --force would be lost.
if [[ -f "$ROOT/autodeploy.lock" ]]; then flock "$ROOT/autodeploy.lock" true; fi
as_deploy /usr/local/bin/ftth-autodeploy "${deploy_args[@]}" || warn "deploy failed; see: journalctl -u ftth-autodeploy"
deployed="$(cat "$ROOT/deployed-sha" 2>/dev/null || true)"
if [[ -z "$deployed" ]]; then
  warn "No images for the latest commit yet (GitHub Actions may still be building, or the GHCR packages are private)."
  warn "The timer retries every 2 minutes. Re-run this same command afterwards to create the admin."
  warn "لسه الـimages ماطلعتش. استنى شوية وشغّل نفس الأمر تاني علشان يعمل الأدمن."
  exit 0
fi
echo "running commit $deployed"

step "Tile server (Martin) / خادم الخرائط"
# Warnings only: a Martin problem must not stop the deploy (ADR-031). Prints no secret; Actions logs are public.
tiles_compose() {
  (cd "$APP" && as_deploy env IMAGE_TAG="$deployed" docker compose --env-file "$ENV_FILE" \
    -f infra/staging/docker-compose.yml --profile tiles "$@")
}
tiles_psql() {
  tiles_compose exec -T postgis psql -U "$(env_get POSTGRES_USER)" -d "$(env_get POSTGRES_DB)" -v ON_ERROR_STOP=1 "$@"
}
if tiles_psql -q >/dev/null 2>&1 <<<"ALTER ROLE ftth_tiles LOGIN PASSWORD '$(env_get FTTH_TILES_PASSWORD)'" &&
  tiles_compose up -d --no-deps martin; then
  for _ in {1..30}; do
    curl -fsS -m 2 -o /dev/null "http://127.0.0.1:$martin_port/health" && break
    sleep 1
  done
  zero=00000000-0000-0000-0000-000000000000
  exp=$(($(date +%s) + 300))
  # Signed the way the API signs (HMAC of source|project|revision|exp); the secret stays inside the container.
  sig="$(tiles_compose exec -T api node -e "process.stdout.write(require('crypto').createHmac('sha256',process.env.TILE_URL_SECRET).update('design_features|$zero|$zero|$exp').digest('base64url'))" 2>/dev/null || true)"
  tile="https://$API_DOMAIN/design_features/14/1/1"
  echo "martin catalog: $(curl -fsS -m 5 "http://127.0.0.1:$martin_port/catalog" | grep -o design_features | head -n 1 || echo missing)"
  echo "tile without signature (expect 401): $(curl -s -m 20 -o /dev/null -w '%{http_code}' "$tile" || true)"
  echo "tile with signature (expect 200 or 204): $(curl -s -m 20 -o /dev/null -w '%{http_code}' "$tile?p=$zero&r=$zero&exp=$exp&sig=$sig" || true)"
  if tiles_psql -c 'SET ROLE ftth_tiles; SELECT 1 FROM users' >/dev/null 2>&1; then
    warn "ftth_tiles can read tables: it must not. / الـrole ده مش المفروض يقرا جداول."
  else
    echo "ftth_tiles cannot read tables: ok"
  fi
else
  warn "Martin did not start; the app is not affected. See: docker compose logs martin"
fi

step "First admin / أول أدمن"
admin_password=""
admin_password_supplied=""
if [[ "${ADMIN_RESET_PASSWORD:-}" == 1 ]]; then
  # Only with a password the operator chose (GitHub secret via ssh-deploy.sh): a generated one would have to be printed.
  [[ -n "${ADMIN_EMAIL:-}" && -n "${ADMIN_PASSWORD_FILE:-}" ]] ||
    die "Admin password reset needs FTTH_ADMIN_EMAIL and FTTH_ADMIN_PASSWORD. / لازم الـsecrets دي علشان نغيّر الباسورد."
  (cd "$APP" && as_deploy env IMAGE_TAG="$deployed" docker compose --env-file "$ENV_FILE" \
    -f infra/staging/docker-compose.yml run --rm --no-deps \
    -e ADMIN_EMAIL="$ADMIN_EMAIL" -e ADMIN_PASSWORD="$(cat "$ADMIN_PASSWORD_FILE")" -e ADMIN_RESET_PASSWORD=1 \
    api node dist/db/create-admin.js) || die "Admin password reset failed. / تغيير باسورد الأدمن فشل."
elif [[ -f "$ROOT/.admin-created" ]]; then
  echo "admin already created earlier (password was shown then)"
elif [[ -z "${ADMIN_EMAIL:-}" ]]; then
  warn "ADMIN_EMAIL not set; skipped. Re-run with ADMIN_EMAIL=you@example.com"
else
  if [[ -n "${ADMIN_PASSWORD_FILE:-}" ]]; then
    # Supplied by ssh-deploy.sh (GitHub secret): used as is and never printed, because Actions logs are public.
    admin_password="$(cat "$ADMIN_PASSWORD_FILE")"
    admin_password_supplied=1
  else
    admin_password="$(openssl rand -base64 24 | tr -d '/+=' | cut -c1-20)"
  fi
  (cd "$APP" && as_deploy env IMAGE_TAG="$deployed" docker compose --env-file "$ENV_FILE" \
    -f infra/staging/docker-compose.yml run --rm --no-deps \
    -e ADMIN_EMAIL="$ADMIN_EMAIL" -e ADMIN_PASSWORD="$admin_password" -e ADMIN_NAME="${ADMIN_NAME:-Administrator}" \
    api node dist/db/create-admin.js) | tee "$ROOT/.admin-result"
  if grep -q "Admin created" "$ROOT/.admin-result"; then
    touch "$ROOT/.admin-created"
  else
    admin_password=""
  fi
  rm -f "$ROOT/.admin-result"
fi

step "Check / فحص"
curl -fsS "http://127.0.0.1:$api_port/health" && echo
curl -fsS -o /dev/null -w "web login page: %{http_code}\n" "http://127.0.0.1:$web_port/ar/login" || true
curl -fsS -o /dev/null -w "https://$APP_DOMAIN: %{http_code}\n" "https://$APP_DOMAIN/ar/login" ||
  warn "HTTPS not answering yet (certificate may take a minute)."

printf '\n\033[1;32m==== Done / تم ====\033[0m\n'
echo "Web:   https://$APP_DOMAIN"
echo "API:   https://$API_DOMAIN/health"
echo "Commit: $deployed"
if [[ -n "$admin_password" && -n "$admin_password_supplied" ]]; then
  echo "Admin: ${ADMIN_EMAIL} (password = GitHub secret FTTH_ADMIN_PASSWORD)"
elif [[ -n "$admin_password" ]]; then
  echo "Admin: ${ADMIN_EMAIL}"
  echo "Password (shown once, save it now / احفظه دلوقتي): $admin_password"
fi
echo "Logs:  journalctl -u ftth-autodeploy -n 50"
